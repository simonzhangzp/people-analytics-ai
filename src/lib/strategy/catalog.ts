export function getCatalogItem(id: string) {
  return strategyCatalog.find((item) => item.id === id);
}

export function filterCatalog(
  items: CatalogItem[],
  query: string,
  kind?: StrategyIntent,
  category?: StrategyCategory | "All",
) {
  const normalized = query.trim().toLowerCase();
  return items.filter((item) => {
    if (kind && item.kind !== kind) return false;
    if (category && category !== "All" && item.category !== category) return false;
    if (!normalized) return true;
    return `${item.title} ${item.statement} ${item.category} ${item.source}`
      .toLowerCase()
      .includes(normalized);
  });
}

export function catalogStats() {
  const byKind = { strategy: 0, problem: 0 };
  const byCategory = Object.fromEntries(
    strategyCategories.map((category) => [category, 0]),
  ) as Record<StrategyCategory, number>;
  for (const item of strategyCatalog) {
    byKind[item.kind] += 1;
    byCategory[item.category] += 1;
  }
  return { total: strategyCatalog.length, byKind, byCategory };
}
