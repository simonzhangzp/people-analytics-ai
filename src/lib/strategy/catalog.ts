function toItem(row: CatalogRow): CatalogItem {
  const [id, kind, category, title, statement, source, sourceUrl, metricIds, population] =
    row;
  return {
    id,
    kind,
    category,
    title,
    statement,
    source,
    sourceUrl,
    metricIds,
    population,
  };
}

export const strategyCatalog: CatalogItem[] = rows.map(toItem);

